import { expect, test } from "@playwright/test";
import { seedAuthedSession, TEST_USER } from "../helpers/auth-seed";
import { installAdminShellMocks, ADMIN_PERMS, paged } from "../helpers/shell-mocks";
const base = "**/api/v1/catalog/cities";
const permissions=["View","Create","Update","Delete"].map(action=>"Permissions.Catalog.Cities."+action);
const br={id:"d6f6541a-3ac0-41eb-b86a-536c2b4c7281",name:"Brasil",iso2Code:"BR",iso3Code:"BRA",numericCode:"076",phoneCode:"+55",isActive:true};
const pt={...br,id:"d6f6541a-3ac0-41eb-b86a-536c2b4c7282",name:"Portugal",iso2Code:"PT",iso3Code:"PRT"};
const sp={id:"d6f6541a-3ac0-41eb-b86a-536c2b4c7291",countryId:br.id,countryName:br.name,name:"São Paulo",code:"SP",ibgeCode:"35",isActive:true};
const foreign={...sp,id:"d6f6541a-3ac0-41eb-b86a-536c2b4c7292",countryId:pt.id,countryName:pt.name,name:"Estado estrangeiro",code:"EXT",ibgeCode:null};
const city={id:"d6f6541a-3ac0-41eb-b86a-536c2b4c7301",stateId:sp.id,stateName:sp.name,countryId:br.id,countryName:br.name,name:"Diadema",ibgeCode:"3513801",isActive:true};
test.beforeEach(async({page})=>{
  const perms=[...ADMIN_PERMS,...permissions,"Permissions.Catalog.Countries.View","Permissions.Catalog.States.View"];
  await seedAuthedSession(page,{...TEST_USER,permissions:perms});
  await installAdminShellMocks(page,perms);
  await page.route("**/api/v1/catalog/countries?*",route=>route.fulfill({json:paged([br,pt])}));
  await page.route("**/api/v1/catalog/states?*",route=>{
    const countryId=new URL(route.request().url()).searchParams.get("countryId");
    const items=countryId===br.id?[sp]:countryId===pt.id?[foreign]:[sp,foreign];
    return route.fulfill({json:paged(items)});
  });
  await page.route(base+"?*",route=>route.fulfill({json:paged([city])}));
});
test("lists cities with state and country and sends dependent filters",async({page})=>{
  await page.goto("/cities");
  await expect(page.getByRole("heading",{name:"Cidades",exact:true})).toBeVisible();
  await expect(page.getByRole("cell",{name:"3513801",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Todos os países",exact:true}).click();
  const countryFiltered=page.waitForRequest(r=>r.url().includes("/cities?")&&r.url().includes("countryId="+br.id));
  await page.getByRole("menuitem",{name:"Brasil",exact:true}).click();await countryFiltered;
  await page.getByRole("button",{name:"Todos os estados",exact:true}).click();
  await expect(page.getByRole("menuitem",{name:"Estado estrangeiro",exact:true})).toHaveCount(0);
  const stateFiltered=page.waitForRequest(r=>r.url().includes("/cities?")&&r.url().includes("stateId="+sp.id));
  await page.getByRole("menuitem",{name:"São Paulo",exact:true}).click();await stateFiltered;
  const searched=page.waitForRequest(r=>r.url().includes("search=Diadema"));
  await page.getByRole("textbox",{name:"Pesquisar cidades"}).fill("Diadema");await searched;
  await page.getByRole("button",{name:"Todas",exact:true}).click();
  const inactive=page.waitForRequest(r=>r.url().includes("isActive=false"));
  await page.getByRole("menuitem",{name:"Inativos",exact:true}).click();await inactive;
});
test("creates Brazilian city with required IBGE and only persists StateId",async({page})=>{
  await page.route(base,route=>route.fulfill({json:city.id}));
  await page.goto("/cities");
  await page.getByRole("button",{name:"Nova cidade",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await dialog.getByRole("button",{name:"País",exact:true}).click();
  await page.getByRole("menuitem",{name:"Brasil",exact:true}).click();
  await dialog.getByRole("button",{name:"Estado",exact:true}).click();
  await page.getByRole("menuitem",{name:"São Paulo",exact:true}).click();
  await dialog.getByRole("textbox",{name:"Cidade",exact:true}).fill("  Diadema  ");
  await dialog.getByRole("button",{name:"Salvar",exact:true}).click();
  await expect(page.locator("#city-ibgeCode-error")).toHaveText("Código IBGE é obrigatório para cidades brasileiras.");
  await dialog.getByRole("textbox",{name:"Código IBGE",exact:true}).fill("3513801");
  const posted=page.waitForRequest(r=>r.method()==="POST"&&r.url().endsWith("/cities"));
  await dialog.getByRole("button",{name:"Salvar",exact:true}).click();
  const payload=(await posted).postDataJSON();
  expect(payload).toEqual({stateId:sp.id,name:"Diadema",ibgeCode:"3513801",isActive:true});
  await expect(dialog).not.toBeVisible();
});
