test("edits, activates and deletes with confirmation",async({page})=>{
  await page.route(base+"/*",route=>route.fulfill({json:city.id}));
  await page.goto("/cities");
  await page.getByRole("button",{name:"Editar Diadema",exact:true}).click();
  await page.getByRole("textbox",{name:"Cidade",exact:true}).fill("Diadema atualizada");
  await expect(page.getByRole("dialog").getByRole("button",{name:"Salvar",exact:true})).toBeEnabled();
  const updated=page.waitForRequest(r=>r.method()==="PUT");
  await page.getByRole("dialog").getByRole("button",{name:"Salvar",exact:true}).click();
  expect((await updated).postDataJSON()).toMatchObject({name:"Diadema atualizada"});
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button",{name:"Desativar",exact:true}).click();
  const disabled=page.waitForRequest(r=>r.method()==="PUT");
  await page.getByRole("dialog").getByRole("button",{name:"Confirmar",exact:true}).click();
  expect((await disabled).postDataJSON()).toMatchObject({isActive:false});
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button",{name:"Excluir Diadema",exact:true}).click();
  const deleted=page.waitForRequest(r=>r.method()==="DELETE");
  await page.getByRole("dialog").getByRole("button",{name:"Excluir",exact:true}).click();await deleted;
  await expect(page.getByRole("dialog")).not.toBeVisible();
});
